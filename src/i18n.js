function normalizeLocale(value) {
  return value === 'en' || value === 'zh-CN' ? value : DEFAULT_LOCALE;
}

function translate(locale, key) {
  const active = DICTIONARIES[normalizeLocale(locale)];
  return active[key] || DICTIONARIES[DEFAULT_LOCALE][key] || '';
}

function issueMessage(locale, code) {
  const key = `issue.${code}`;
  return DICTIONARIES[DEFAULT_LOCALE][key] ? translate(locale, key) : translate(locale, 'issue.invalid_article');
}

function resultMessage(locale, result, context = 'publish') {
  const value = result && typeof result === 'object' ? result : {};
  const reasonKey = typeof value.reason === 'string' ? `reason.${value.reason}` : '';
  const knownReason = reasonKey && Object.hasOwn(DICTIONARIES[DEFAULT_LOCALE], reasonKey);
  const issueKey = typeof value.reason === 'string' ? `issue.${value.reason}` : '';
  const knownIssue = issueKey && Object.hasOwn(DICTIONARIES[DEFAULT_LOCALE], issueKey);
  if (value.status === 'connected') return translate(locale, 'notice.connectionSucceeded');
  if (value.status === 'restored') return translate(locale, 'action.associationRestored');
  if (value.manualRequired === true) return translate(locale, 'action.manualCheck');
  if (knownReason) return translate(locale, reasonKey);
  if (knownIssue) return translate(locale, issueKey);
  if (value.status === 'published') return translate(locale, 'action.published');
  if (value.status === 'conflict') return translate(locale, 'action.conflict');
  if (value.status === 'draft' && value.canResume === true) return translate(locale, 'action.draftReady');
  if (value.status === 'draft') return translate(locale, 'action.draftNotPublished');
  if (value.status === 'needs-check') return translate(locale, 'action.needsCheck');
  if (context === 'connection') return translate(locale, 'notice.connectionFailed');
  if (context === 'restore') return translate(locale, 'action.associationFailed');
  return translate(locale, 'action.unpublished');
}

module.exports = { DEFAULT_LOCALE, LANGUAGES, DICTIONARIES, normalizeLocale, translate, issueMessage, resultMessage };
